-- Run after the workload with -v lsn0=<pg_current_wal_lsn before>.
\pset footer off
\echo == totals (pg_stat_statements, this database)
SELECT sum(calls) AS calls,
       sum(shared_blks_hit + shared_blks_read) AS buffers,
       sum(shared_blks_dirtied) AS dirtied,
       sum(temp_blks_written) AS temp_written,
       sum(wal_records) AS wal_records,
       sum(wal_bytes) AS wal_bytes,
       sum(wal_fpi) AS wal_fpi
FROM pg_stat_statements s JOIN pg_database d ON d.oid = s.dbid
WHERE d.datname = current_database();

\echo == top statements by buffers
SELECT calls, rows,
       shared_blks_hit + shared_blks_read AS buffers,
       round(100.0 * (shared_blks_hit + shared_blks_read)
             / sum(shared_blks_hit + shared_blks_read) OVER (), 1) AS pct_buf,
       round(100.0 * calls / sum(calls) OVER (), 1) AS pct_calls,
       shared_blks_dirtied AS dirtied, wal_records, wal_bytes,
       round(100.0 * wal_bytes / nullif(sum(wal_bytes) OVER (), 0), 1) AS pct_wal,
       left(regexp_replace(query, '\s+', ' ', 'g'), 110) AS query
FROM pg_stat_statements s JOIN pg_database d ON d.oid = s.dbid
WHERE d.datname = current_database()
ORDER BY buffers DESC, query
LIMIT 12;

\echo == top statements by calls
SELECT calls, rows, wal_bytes, left(regexp_replace(query, '\s+', ' ', 'g'), 110) AS query
FROM pg_stat_statements s JOIN pg_database d ON d.oid = s.dbid
WHERE d.datname = current_database()
ORDER BY calls DESC, query
LIMIT 12;

\echo == top statements by WAL bytes
SELECT calls, wal_records, wal_bytes, wal_fpi,
       round(100.0 * wal_bytes / nullif(sum(wal_bytes) OVER (), 0), 1) AS pct_wal,
       left(regexp_replace(query, '\s+', ' ', 'g'), 110) AS query
FROM pg_stat_statements s JOIN pg_database d ON d.oid = s.dbid
WHERE d.datname = current_database()
ORDER BY wal_bytes DESC, query
LIMIT 8;

\echo == WAL generated by the run (pg_current_wal_lsn delta, whole cluster)
SELECT pg_wal_lsn_diff(pg_current_wal_lsn(), :'lsn0') AS wal_bytes_lsn_delta;

\echo == pg_stat_user_tables
SELECT relname, seq_scan, seq_tup_read, idx_scan, n_tup_ins, n_tup_upd, n_tup_hot_upd,
       n_live_tup, n_dead_tup
FROM pg_stat_user_tables ORDER BY relname;

\echo == pg_statio_user_tables
SELECT relname, heap_blks_read + heap_blks_hit AS heap_blks,
       idx_blks_read + idx_blks_hit AS idx_blks,
       coalesce(toast_blks_read + toast_blks_hit, 0) AS toast_blks
FROM pg_statio_user_tables ORDER BY relname;

\echo == subscription table size
SELECT pg_relation_size('autumn_webhook_subscriptions') AS heap_bytes,
       pg_relation_size('autumn_webhook_subscriptions') / 8192 AS heap_pages;

\echo == subscription state (equivalence: ordered md5 of every row)
SELECT md5(string_agg(id || '|' || status || '|' || consecutive_failures, ',' ORDER BY id))
       AS subscriptions_md5,
       sum(consecutive_failures) AS failures_total,
       count(*) FILTER (WHERE status = 'active') AS active
FROM autumn_webhook_subscriptions;
SELECT md5(string_agg(id || '|' || coalesce(response_status::text, '-') || '|' || attempt
                      || '|' || is_dlq || '|' || coalesce(last_error, '-') || '|' || logged_at,
                      ',' ORDER BY id)) AS deliveries_md5,
       count(*) AS deliveries
FROM autumn_webhook_deliveries;
