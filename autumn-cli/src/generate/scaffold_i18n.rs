    /// A `.ftl` is a file people edit. A translator who groups keys with a
    /// blank line, or leaves a note beside one, must not move the boundary of
    /// what `destroy` owns — otherwise it strands the keys below the separator
    /// with no call sites, and `autumn i18n check --strict` starts failing on
    /// keys whose owner nobody can find.
    /// A `--force` regeneration that dropped a field or a flag must not leave
    /// the keys for those surfaces behind: nothing references them any more, so
    /// `autumn i18n check --strict` fails on them.
    #[test]
    fn regeneration_prunes_keys_whose_surfaces_are_gone() {
        let before = merge_en_ftl(
            "",
            "Post",
            "post",
            &keys(&[
                ("common.create", "Create"),
                ("post.new", "New Post"),
                ("post.field.body", "Body"),
                ("post.search.title", "Search Posts"),
            ]),
        );
        // A translated value, and a note beside a key that survives.
        let edited = before
            .replace("post.new = New Post", "post.new = Nouvel article")
            .replace(
                "post.field.body = Body\n",
                "# on the edit form\npost.field.body = Body\n",
            );
        let after = merge_en_ftl(
            &edited,
            "Post",
            "post",
            &keys(&[("common.create", "Create"), ("post.new", "New Post")]),
        );
        assert!(!after.contains("post.field.body"), "{after}");
        assert!(!after.contains("post.search.title"), "{after}");
        assert!(
            after.contains("post.new = Nouvel article"),
            "a translated value must survive:\n{after}"
        );
        assert!(
            after.contains("# on the edit form"),
            "a translator's note must survive:\n{after}"
        );
        // Chrome is never pruned from here — a sibling resource writes it too.
        assert!(after.contains("common.create = Create"), "{after}");
        // And it settles: regenerating again changes nothing.
        assert_eq!(
            merge_en_ftl(
                &after,
                "Post",
                "post",
                &keys(&[("common.create", "Create"), ("post.new", "New Post")])
            ),
            after
        );
    }

    /// A Fluent continuation is just indented text and usually carries no `=`.
    /// Keeping one whose key was pruned orphans it — the loader either rejects
    /// the bundle (a startup panic, via `.i18n_auto()`) or glues the text onto
    /// the message above, rewriting an unrelated translation.
    #[test]
    fn regeneration_drops_continuation_lines_with_their_pruned_key() {
        let before = merge_en_ftl(
            "",
            "Post",
            "post",
            &keys(&[("post.new", "New Post"), ("post.field.body", "Body")]),
        );
        // A wrapped value with NO `=` in the continuation, and a kept key that
        // also wraps — the first must go, the second must stay whole.
        let edited = before
            .replace(
                "post.field.body = Body\n",
                "post.field.body = Body\n    spilling over onto a second line\n",
            )
            .replace(
                "post.new = New Post\n",
                "post.new = New Post\n    also wrapped\n",
            );
        let after = merge_en_ftl(&edited, "Post", "post", &keys(&[("post.new", "New Post")]));
        assert!(!after.contains("post.field.body"), "{after}");
        assert!(
            !after.contains("spilling over"),
            "the pruned key's continuation must go with it:\n{after}"
        );
        assert!(
            after.contains("also wrapped"),
            "a surviving key keeps its own continuation:\n{after}"
        );
    }

    #[test]
