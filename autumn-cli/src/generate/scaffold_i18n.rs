//! Translatable view emission for `autumn generate scaffold --i18n` (issue #1349).
//!
//! Autumn already ships the whole Fluent stack — the [`t!`] macro with
//! compile-time key validation, `Locale::t()`, the `i18n/<tag>.ftl` convention,
//! fallback chains, and an `Accept-Language` `Locale` extractor. What the
//! scaffold generator lacked was the wiring: every generated view emitted
//! hardcoded English, so localizing a resource meant hand-ripping the English
//! out of four views and hand-authoring the matching `.ftl` keys.
//!
//! [`ViewLabels`] is the single seam that closes that gap. Every user-facing
//! string in the generated views goes through it, and it emits one of two
//! things:
//!
//! * **`--i18n` off** — the caller's `plain` expression, returned *verbatim*.
//!   Byte-for-byte identity with the pre-#1349 scaffold is therefore structural,
//!   not a property some test has to keep re-checking: with the flag off this
//!   type is a `str -> str` identity function.
//! * **`--i18n` on** — a `t!(locale, "key")` lookup, and the key/English pair is
//!   recorded so [`merge_en_ftl`] can back-fill `i18n/en.ftl` with exactly the
//!   keys the views reference. That matters beyond tidiness: `t!` validates key
//!   existence *at compile time*, so a key the generator references but does not
//!   define is a `compile_error!` in the user's app, not a runtime miss.
//!
//! Because the English value written to `en.ftl` and the English rendered by the
//! non-i18n scaffold come from the same call site, an `en` app renders
//! identically either way (AC4) — there is no second copy of the strings to
//! drift.
//!
//! [`t!`]: autumn_web::t

use std::cell::RefCell;
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use super::scaffold::{is_raw_string_start, skip_raw_string};

/// The comment introducing the shared-chrome block in a generated `en.ftl`.
const COMMON_HEADER: &str = "# Shared chrome — reused by every scaffolded resource.";

/// Prefix of the comment introducing one resource's block in a generated
/// `en.ftl`. The resource's `PascalCase` name and a trailing marker follow, so
/// `autumn destroy scaffold` can find and remove exactly the block it added.
const RESOURCE_HEADER_PREFIX: &str = "# ";

/// Trailer stamped on a generated resource block's comment so the destroy path
/// can identify it without guessing.
const RESOURCE_HEADER_SUFFIX: &str = " — generated by `autumn generate scaffold --i18n`.";

/// Closes the shared-chrome block.
const COMMON_FOOTER: &str = "# — end shared chrome —";

/// Closes a resource's block. The `PascalCase` name goes between the two
/// halves, mirroring its header.
const RESOURCE_FOOTER_PREFIX: &str = "# — end ";
const RESOURCE_FOOTER_SUFFIX: &str = " —";

/// The comment closing the block `header` opens.
///
/// Blocks are explicitly CLOSED rather than run to the first blank line or
/// comment, because a `.ftl` is a file people edit: a translator who groups
/// keys with a blank line, or leaves a `# careful, this one is on a button`
/// note beside one, would otherwise move the boundary. `destroy` would then
/// take the header and the keys above the separator and strand the rest — with
/// no call sites left, so `autumn i18n check --strict` starts failing on keys
/// nobody can find the owner of. An explicit marker lets formatting and
/// comments live inside the block while everything outside it stays the
/// application's own.
fn block_footer(header: &str) -> String {
    if header == COMMON_HEADER {
        return COMMON_FOOTER.to_owned();
    }
    let pascal = header
        .strip_prefix(RESOURCE_HEADER_PREFIX)
        .and_then(|rest| rest.strip_suffix(RESOURCE_HEADER_SUFFIX))
        .unwrap_or_default();
    format!("{RESOURCE_FOOTER_PREFIX}{pascal}{RESOURCE_FOOTER_SUFFIX}")
}

/// Emits every user-facing string in a generated view, either as the literal
/// English expression the plain scaffold uses or as a `t!(locale, "key")`
/// lookup.
///
/// See the [module docs](self) for why the `plain` expression is threaded
/// through rather than reconstructed.
#[derive(Debug)]
pub(super) struct ViewLabels {
    /// Whether `--i18n` is on. `false` makes every emitter method an identity
    /// function over its `plain` argument.
    enabled: bool,
    /// Keys actually referenced, mapped to the English value that must appear in
    /// `i18n/en.ftl`. Interior mutability so the emitters stay `&self` and can be
    /// threaded through the generator's `fn(&…) -> String` render helpers.
    used: RefCell<BTreeMap<String, String>>,
}

impl ViewLabels {
    /// A disabled emitter — every method returns its `plain` argument verbatim.
    pub(super) const fn disabled() -> Self {
        Self {
            enabled: false,
            used: RefCell::new(BTreeMap::new()),
        }
    }

    /// An emitter that translates. `enabled` is the `--i18n` flag, threaded
    /// rather than assumed so callers can build one emitter unconditionally.
    pub(super) const fn new(enabled: bool) -> Self {
        Self {
            enabled,
            used: RefCell::new(BTreeMap::new()),
        }
    }

    /// Whether this emitter translates.
    pub(super) const fn enabled(&self) -> bool {
        self.enabled
    }

    /// The key -> English map for every key the views actually referenced.
    ///
    /// Exactly this set is written to `en.ftl`: a key the generator never
    /// emitted would show up as "unused" under `autumn i18n check` (#1252), and
    /// a key it emitted but never defined would fail the user's build.
    pub(super) fn used_keys(&self) -> BTreeMap<String, String> {
        self.used.borrow().clone()
    }

    /// Record `key = ftl` and return the `t!` invocation for it.
    fn record(&self, key: &str, ftl: &str, args: &[(&str, &str)]) -> String {
        self.used
            .borrow_mut()
            .insert(key.to_owned(), ftl.to_owned());
        if args.is_empty() {
            format!("t!(locale, \"{key}\")")
        } else {
            let rendered: Vec<String> = args
                .iter()
                .map(|(name, expr)| format!("{name} = {expr}"))
                .collect();
            format!("t!(locale, \"{key}\", {})", rendered.join(", "))
        }
    }

    /// A string-valued site (`impl Into<String>` parameters such as
    /// `a11y::Link::new`/`Button::new`, `FormFor::override_label`, and Maud
    /// splice positions). `english` is the bare text; with `--i18n` off it is
    /// emitted as a quoted Rust literal, exactly as before.
    pub(super) fn lit(&self, key: &str, english: &str) -> String {
        if self.enabled {
            self.record(key, english, &[])
        } else {
            format!("\"{english}\"")
        }
    }

    /// [`Self::lit`] for a `&str` parameter (`layout(title)`,
    /// `widgets::Column::new`, `property_list` labels).
    pub(super) fn lit_ref(&self, key: &str, english: &str) -> String {
        if self.enabled {
            format!("&{}", self.record(key, english, &[]))
        } else {
            format!("\"{english}\"")
        }
    }

    /// [`Self::lit`] in Maud **body** position, where a bare literal renders as
    /// text but any expression must be parenthesised: `"Save"` becomes
    /// `(t!(locale, "common.save"))`.
    pub(super) fn markup(&self, key: &str, english: &str) -> String {
        if self.enabled {
            format!("({})", self.record(key, english, &[]))
        } else {
            format!("\"{english}\"")
        }
    }

    /// [`Self::expr`] in Maud body position.
    pub(super) fn markup_expr(
        &self,
        key: &str,
        ftl: &str,
        plain: &str,
        args: &[(&str, &str)],
    ) -> String {
        if self.enabled {
            format!("({})", self.record(key, ftl, args))
        } else {
            plain.to_owned()
        }
    }

    /// The general form: `plain` is the **complete** Rust expression the
    /// non-i18n scaffold emits (often a `format!(…)` call), `ftl` the Fluent
    /// value — which may carry `{ $arg }` placeholders fed by `args`, each a
    /// `(fluent name, Rust expression)` pair.
    pub(super) fn expr(&self, key: &str, ftl: &str, plain: &str, args: &[(&str, &str)]) -> String {
        if self.enabled {
            self.record(key, ftl, args)
        } else {
            plain.to_owned()
        }
    }

    /// [`Self::expr`] for a `&str` parameter.
    pub(super) fn expr_ref(
        &self,
        key: &str,
        ftl: &str,
        plain: &str,
        args: &[(&str, &str)],
    ) -> String {
        if self.enabled {
            format!("&{}", self.record(key, ftl, args))
        } else {
            plain.to_owned()
        }
    }
}

/// Split a `.ftl` source into its defined keys.
///
/// Mirrors the minimal parser in `autumn-macros`' `t!` validation and
/// `autumn-web`'s `Bundle` loader: a top-level `key = value` line, with `#`
/// comments and indented continuation lines skipped.
pub(super) fn defined_keys(src: &str) -> BTreeMap<String, String> {
    src.lines()
        .filter(|line| {
            !line.trim_start().starts_with('#')
                && !line.trim().is_empty()
                && !line.starts_with(' ')
                && !line.starts_with('\t')
        })
        .filter_map(|line| line.split_once('='))
        .map(|(k, v)| (k.trim().to_owned(), v.trim().to_owned()))
        .collect()
}

/// Merge the keys a `--i18n` scaffold referenced into `existing` (the project's
/// `i18n/en.ftl`, or `""` when there is none yet).
///
/// Semantics, in order of importance:
///
/// 1. **A key that already exists is never rewritten.** Re-running the
///    generator over a file whose English has been edited — or whose keys a
///    translator has already worked from — must not clobber it.
/// 2. **Shared chrome is written once.** `common.*` keys land in one block that
///    later resources add to rather than duplicate (AC5).
/// 3. **The resource's own keys are grouped** under a marked comment, so a
///    translator reads the file by resource and `autumn destroy scaffold` can
///    remove exactly what this generator added.
///
/// Returns `existing` unchanged when every key is already defined, so the
/// generator can skip the write and leave the file out of the plan.
pub(super) fn merge_en_ftl(
    existing: &str,
    pascal_name: &str,
    resource: &str,
    keys: &BTreeMap<String, String>,
) -> String {
    use std::fmt::Write as _;

    let already = defined_keys(existing);
    let resource_prefix = format!("{resource}.");
    let resource_header = format!("{RESOURCE_HEADER_PREFIX}{pascal_name}{RESOURCE_HEADER_SUFFIX}");
    // A resource literally named `Common` would share its prefix with the chrome
    // block. `plan_scaffold_with_options_impl` refuses that name under `--i18n`;
    // classifying chrome FIRST and taking the resource's keys from what is left
    // is the belt-and-braces half, so no key can ever be written to both blocks
    // even from a hand-built plan.
    let missing_common: Vec<(&String, &String)> = keys
        .iter()
        .filter(|(k, _)| k.starts_with("common.") && !already.contains_key(*k))
        .collect();
    let missing_resource: Vec<(&String, &String)> = keys
        .iter()
        .filter(|(k, _)| {
            k.starts_with(&resource_prefix)
                && !k.starts_with("common.")
                && !already.contains_key(*k)
        })
        .collect();
    // Reconciled BEFORE the nothing-to-do check below: a regeneration that
    // dropped a field or a flag has every REMAINING key already present, so the
    // "missing" sets are empty while the block still carries keys the rewritten
    // routes no longer reference — exactly what `autumn i18n check --strict`
    // fails on. Values, comments, and blank lines for surviving keys carry over.
    //
    // The shared chrome is never pruned here: every resource writes those keys,
    // so dropping one from this resource's render would delete a key a SIBLING
    // still uses. Chrome is additive, and `destroy` is what eventually takes it.
    if let Some(reconciled) = reconcile_block(existing, &resource_header, &resource_prefix, keys) {
        return merge_en_ftl(&reconciled, pascal_name, resource, keys);
    }
    if missing_common.is_empty() && missing_resource.is_empty() {
        return existing.to_owned();
    }

    // Re-running the generator — after adding a column, or with a flag that
    // brings new chrome — must extend the block that already exists rather than
    // strand the new key at EOF under no header at all. The file's whole promise
    // to a translator is that it reads by section.
    if !missing_common.is_empty()
        && let Some(insert_at) = block_end(existing, COMMON_HEADER)
    {
        let mut out = String::with_capacity(existing.len() + missing_common.len() * 48);
        out.push_str(&existing[..insert_at]);
        for (key, value) in &missing_common {
            let _ = writeln!(out, "{key} = {value}");
        }
        out.push_str(&existing[insert_at..]);
        // Whatever the resource block still needs lands on the next pass, which
        // terminates: the chrome keys are now all present.
        return merge_en_ftl(&out, pascal_name, resource, keys);
    }

    let mut out = String::with_capacity(existing.len() + (keys.len() + 4) * 48);
    if existing.is_empty() {
        out.push_str(
            "# Generated by `autumn generate scaffold --i18n`.\n\
             #\n\
             # This is the DEFAULT locale — leave these values in their own language.\n\
             # To add a locale, copy this file to `i18n/<tag>.ftl` and translate THERE.\n\
             # Keys are grouped by resource; `common.*` is shared chrome every\n\
             # scaffolded resource reuses.\n\n",
        );
    } else {
        out.push_str(existing);
        if !out.ends_with('\n') {
            out.push('\n');
        }
        out.push('\n');
    }

    if !missing_common.is_empty() {
        out.push_str(COMMON_HEADER);
        out.push('\n');
        for (key, value) in missing_common {
            let _ = writeln!(out, "{key} = {value}");
        }
        out.push_str(COMMON_FOOTER);
        out.push('\n');
        if !missing_resource.is_empty() {
            out.push('\n');
        }
    }
    if !missing_resource.is_empty() {
        if !existing.contains(&resource_header) {
            out.push_str(&resource_header);
            out.push('\n');
        }
        for (key, value) in missing_resource {
            let _ = writeln!(out, "{key} = {value}");
        }
        out.push_str(&block_footer(&resource_header));
        out.push('\n');
    }
    out
}

/// Rewrite the block `header` opens so its keys are exactly `keys`' entries
/// under `prefix`, or `None` when there is no such block or it already matches.
///
/// Existing VALUES win — a translated `post.new = Nouvel article` stays put —
/// and non-key lines (a translator's comment, a blank line grouping fields) are
/// carried through in place. Only keys the current render no longer references
/// are dropped, which is the whole point: they have no call sites left, so
/// `autumn i18n check --strict` would fail on them.
fn reconcile_block(
    existing: &str,
    header: &str,
    prefix: &str,
    keys: &BTreeMap<String, String>,
) -> Option<String> {
    use std::fmt::Write as _;
    let end = block_end(existing, header)?;
    let start = existing.find(header)?;
    let body_start = start + existing[start..].find('\n').map_or(0, |i| i + 1);
    // The `common.` exclusion applies only when reconciling a RESOURCE block —
    // a resource named `Common` is refused, but a hand-built plan could still
    // reach here. Pruning the chrome block passes `prefix == "common."`, where
    // the exclusion must not fire.
    let wanted: BTreeMap<&str, &str> = keys
        .iter()
        .filter(|(k, _)| {
            k.starts_with(prefix) && (prefix == "common." || !k.starts_with("common."))
        })
        .map(|(k, v)| (k.as_str(), v.as_str()))
        .collect();

    let mut body = String::new();
    let mut keeping_continuations = false;
    for line in existing[body_start..end].lines() {
        // INDENTATION decides first, before any `=` split. A Fluent
        // continuation is just indented text and usually contains no `=` at
        // all (`    and a second line`), so testing for `=` first would file it
        // as a comment and keep it even when its key is being dropped —
        // producing exactly the orphan this reconciliation exists to avoid:
        // the loader either rejects it or silently glues it onto the message
        // above.
        if line.starts_with(' ') || line.starts_with('\t') {
            if keeping_continuations {
                body.push_str(line);
                body.push('\n');
            }
            continue;
        }
        // COMMENTS are tested before the `=` split, and do not end a value.
        // Both halves matter, and both mirror `parse_ftl` (`autumn/src/i18n.rs`)
        // rather than guessing:
        //
        //   * A comment carrying an `=` (`# use post.x = y here`) would
        //     otherwise be read as a key line, found absent from `wanted`, and
        //     deleted — taking a translator's note with it.
        //   * `parse_ftl` `continue`s past a comment WITHOUT flushing the
        //     current key, so an indented line after a mid-value comment is
        //     still part of that value at runtime. Ending the value here would
        //     drop the continuation and silently truncate the translation.
        //
        // A BLANK line does flush there, so it still ends the value here.
        if line.trim_start().starts_with('#') {
            body.push_str(line);
            body.push('\n');
            continue;
        }
        let Some((raw_key, _)) = line.split_once('=') else {
            // A blank line at the block's own indentation — keep it where the
            // translator put it. It ends the previous key's value.
            keeping_continuations = false;
            body.push_str(line);
            body.push('\n');
            continue;
        };
        if wanted.contains_key(raw_key.trim()) {
            keeping_continuations = true;
            body.push_str(line);
            body.push('\n');
        } else {
            // Dropped: its continuation lines go with it.
            keeping_continuations = false;
        }
    }
    // Scanned over the WHOLE file, not just this block. A key can be defined
    // outside the block a translator never touched — hand-authored above it, or
    // left behind by an older layout — and appending a second definition here
    // would not merely duplicate it: `parse_ftl` inserts each entry into a map
    // in file order (`autumn/src/i18n.rs`), so the LAST definition wins. The
    // generated English would silently replace the translation above it, which
    // is the one thing this merge promises never to do. Reconciliation itself
    // still reads only the block: keys outside it are not the generator's to
    // keep or drop, just its to leave alone.
    let defined_anywhere = defined_keys(existing);
    for (key, value) in &wanted {
        if !defined_anywhere.contains_key(*key) {
            let _ = writeln!(body, "{key} = {value}");
        }
    }

    if body == existing[body_start..end] {
        return None;
    }
    let mut out = String::with_capacity(existing.len());
    out.push_str(&existing[..body_start]);
    out.push_str(&body);
    out.push_str(&existing[end..]);
    Some(out)
}

/// Byte offset just past the last key line of the block `header` introduces, or
/// `None` when `existing` carries no such block. Used for both the shared
/// chrome block and a resource's own.
///
/// The block runs from its header to the first blank line or foreign comment —
/// the same shape [`merge_en_ftl`] writes.
fn block_end(existing: &str, header: &str) -> Option<usize> {
    let start = existing.find(header)?;
    let mut cursor = start + header.len();
    // Step past the header's own newline.
    cursor += existing[cursor..].find('\n').map_or(0, |i| i + 1);
    let footer = block_footer(header);
    let mut end = cursor;
    for line in existing[cursor..].split_inclusive('\n') {
        if line.trim_end() == footer {
            return Some(end);
        }
        end += line.len();
    }
    // No footer: a bundle written before blocks were explicitly closed. Fall
    // back to the old boundary — the first blank line or foreign comment — so
    // an existing project still merges and destroys correctly.
    let mut end = cursor;
    for line in existing[cursor..].split_inclusive('\n') {
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            break;
        }
        end += line.len();
    }
    Some(end)
}

/// Inverse of [`merge_en_ftl`] for `autumn destroy scaffold` — remove one
/// resource's block (its marked comment plus every `<resource>.` key) from
/// `existing`.
///
/// The shared `common.*` block is deliberately left alone: other scaffolded
/// resources reuse it, and it is what keeps the file non-empty. That matters —
/// the generated app calls `.i18n_auto()`, which panics at startup if the
/// default locale's file is missing, so destroy must never empty or delete it.
pub(super) fn remove_en_ftl_keys(
    existing: &str,
    pascal_name: &str,
    resource: &str,
    // Every key surviving project source still looks up — the resource's own as
    // much as the shared chrome. The caller scans the project for these,
    // because the bundle itself cannot answer it: a resource whose keys were
    // all hand-authored before it was scaffolded leaves no marker comment
    // behind, so "no other marker" does NOT mean "no other user".
    surviving: &std::collections::HashSet<String>,
) -> String {
    let stripped = prune_resource_block(existing, pascal_name, resource, surviving);
    // Chrome exists to be shared. Once nothing references it, every `common.*`
    // key is dead weight — which is exactly what `autumn i18n check --strict`
    // fails on, so destroying the only `--i18n` resource would otherwise leave
    // the project's own lint red. But the asymmetry matters: an orphan key is a
    // lint warning, while removing one a surviving resource still calls is a
    // COMPILE error (`t!` validates key existence at compile time). So this errs
    // toward keeping.
    //
    // Never the FILE, either way: `.i18n_auto()` panics at startup when the
    // default locale's bundle is missing, and a comment-only bundle still loads.
    prune_chrome_block(&stripped, surviving)
}

/// Narrow the shared chrome block to the keys `surviving` still names, dropping
/// the block entirely when nothing is left.
///
/// Per KEY, not all-or-nothing. Chrome is per-surface: `common.trash`,
/// `common.restore` and `common.purge` come from `--soft-delete`, `common.next`
/// from the pager, `common.export.csv` from the CSV link. Destroying the only
/// resource that had a Trash view leaves those three referenced by nothing —
/// which `autumn i18n check --strict` fails on — while `common.create`,
/// `common.save` and the rest are still in use by every sibling and must stay.
///
/// Marker-bounded like [`remove_marked_block`], so a hand-authored `common.*`
/// key outside the block is never touched.
fn prune_chrome_block(existing: &str, surviving: &std::collections::HashSet<String>) -> String {
    prune_block(existing, COMMON_HEADER, "common.", surviving)
}

/// Narrow one resource's block to the keys `surviving` still names, dropping
/// the block entirely when nothing is left.
///
/// Per KEY for the same reason the chrome block is, and it is the same failure:
/// hand-written code outside the generated module can reference a generated
/// key — `t!(locale, "post.index.title")` on a dashboard card or a nav link is
/// an ordinary thing for an app to do — and taking the whole `post.*` block out
/// from under it breaks the build, because `t!` validates key existence at
/// COMPILE time. Restricting preservation to `common.*` drew the line in the
/// wrong place: nothing about a `post.` prefix makes a live call site less
/// live. Keys nothing references still go, so `autumn i18n check --strict` does
/// not go red on the leftovers.
fn prune_resource_block(
    existing: &str,
    pascal_name: &str,
    resource: &str,
    surviving: &std::collections::HashSet<String>,
) -> String {
    let header = format!("{RESOURCE_HEADER_PREFIX}{pascal_name}{RESOURCE_HEADER_SUFFIX}");
    prune_block(existing, &header, &format!("{resource}."), surviving)
}

/// Shared body of [`prune_chrome_block`] and [`prune_resource_block`]: keep the
/// block's keys that `surviving` names under `prefix`, drop the rest, and take
/// the whole marked block out when that leaves nothing.
///
/// Marker-bounded like [`remove_marked_block`], so a hand-authored key outside
/// the block is never touched.
fn prune_block(
    existing: &str,
    header: &str,
    prefix: &str,
    surviving: &std::collections::HashSet<String>,
) -> String {
    // Only keys the bundle actually DEFINES. `surviving` is a scan of source,
    // so it can name a key no `.ftl` carries — a call site that was already
    // failing `t!` before any of this ran — and `reconcile_block` appends keys
    // it does not find defined. Destroy inventing an empty message for one is
    // strictly worse than leaving the pre-existing breakage alone.
    let defined = defined_keys(existing);
    let kept: BTreeMap<String, String> = surviving
        .iter()
        .filter(|key| key.starts_with(prefix) && defined.contains_key(*key))
        .map(|key| (key.clone(), String::new()))
        .collect();
    if kept.is_empty() {
        return remove_marked_block(existing, header);
    }
    // `reconcile_block` keeps each surviving key's own value and drops the
    // rest — the empty values above are never written, since every key it keeps
    // is already defined.
    reconcile_block(existing, header, prefix, &kept).unwrap_or_else(|| existing.to_owned())
}

/// Remove the marked comment `header` and the run of key lines it introduces.
///
/// Bounded by the MARKER, not by key prefix. A prefix sweep would also delete a
/// hand-authored `post.email.subject` — a translation the application owns,
/// which this generator never wrote and has no business removing — purely
/// because it happens to start with the resource's name. The merge path goes to
/// some trouble never to overwrite a value somebody else authored; destroy has
/// to be equally careful about what it takes away. So removal covers exactly
/// the block `merge_en_ftl` writes: the header line, then every following line
/// up to the first blank line or foreign comment.
///
/// That run includes any INDENTED continuation lines. Leaving those behind is
/// how a destroy corrupts a bundle: the loader either rejects the orphan
/// outright — and `.i18n_auto()` turns that into a startup panic — or silently
/// glues it onto whichever key precedes it, rewriting an unrelated translation.
fn remove_marked_block(existing: &str, header: &str) -> String {
    let Some(end) = block_end(existing, header) else {
        return existing.to_owned();
    };
    let start = existing.find(header).expect("block_end found the header");
    // `block_end` stops just BEFORE the closing marker; take that line too.
    let footer = block_footer(header);
    let end = existing[end..]
        .strip_prefix(footer.as_str())
        .map_or(end, |rest| {
            end + footer.len() + usize::from(rest.starts_with('\n'))
        });
    let mut out = String::with_capacity(existing.len());
    out.push_str(&existing[..start]);
    out.push_str(&existing[end..]);
    let lines: Vec<&str> = out.lines().collect();
    collapse_blank_runs(&lines)
}

/// Re-join `lines`, collapsing the blank runs a removed block leaves behind and
/// restoring the file's single trailing newline.
fn collapse_blank_runs(lines: &[&str]) -> String {
    let mut joined = String::with_capacity(lines.iter().map(|l| l.len() + 1).sum());
    let mut prev_blank = false;
    for line in lines {
        let blank = line.trim().is_empty();
        if blank && prev_blank {
            continue;
        }
        prev_blank = blank;
        joined.push_str(line);
        joined.push('\n');
    }
    while joined.ends_with("\n\n") {
        joined.pop();
    }
    joined
}

/// The name of the TOML table `line` opens, if it opens one.
///
/// Tolerates the spacing and trailing comments TOML allows — `[ i18n ]` and
/// `[i18n] # locale settings` are both the i18n table. Getting this wrong is not
/// cosmetic: missing an existing table makes the generator append a SECOND
/// `[i18n]`, and a duplicate table makes the whole file unparseable, taking the
/// application's entire configuration down with it.
fn toml_table_name(line: &str) -> Option<&str> {
    let trimmed = line.trim();
    let rest = trimmed.strip_prefix('[')?;
    let close = rest.find(']')?;
    // Anything after the closing bracket must be blank or a comment — otherwise
    // this is not a table header at all.
    let tail = rest[close + 1..].trim();
    if !tail.is_empty() && !tail.starts_with('#') {
        return None;
    }
    // `["i18n"]` names the same table as `[i18n]` — TOML lets any key be
    // quoted. Left quoted, the name never matches, so the caller concludes
    // there is no `[i18n]` table and appends one: a SECOND definition of the
    // same table, which makes `autumn.toml` unparseable for the app that has
    // to read it.
    let name = rest[..close].trim();
    Some(
        name.strip_prefix('"')
            .and_then(|n| n.strip_suffix('"'))
            .or_else(|| name.strip_prefix('\'').and_then(|n| n.strip_suffix('\'')))
            .unwrap_or(name),
    )
}

/// A TOML key with any quoting removed.
///
/// `"default_locale" = "fr"` is the same key as `default_locale = "fr"` — TOML
/// lets any key be quoted, and serde's loader reads both. Compared with its
/// quotes still on, the key never matches and the generator falls back to `en`,
/// writing its output where the runtime does not look.
fn toml_key_name(raw: &str) -> &str {
    let key = raw.trim();
    key.strip_prefix('"')
        .and_then(|k| k.strip_suffix('"'))
        .or_else(|| key.strip_prefix('\'').and_then(|k| k.strip_suffix('\'')))
        .unwrap_or(key)
}

/// The scalar on the right of a TOML `key = value`, unquoted, with any trailing
/// comment removed.
///
/// The comment has to be stripped with the quoting in mind, not before it: `#`
/// is an ordinary character inside a string, so cutting at the first `#` would
/// mangle `dir = "i18n#v2"`, while ignoring comments entirely turns
/// `default_locale = "fr" # our default` into the locale tag
/// `fr" # our default` — and the generator would then cheerfully create a file
/// named after it. Returns `None` for an empty or unparseable value.
fn toml_scalar_value(raw: &str) -> Option<String> {
    let trimmed = raw.trim_start();
    let quote = trimmed.chars().next()?;
    let value = if quote == '"' || quote == '\'' {
        let rest = &trimmed[quote.len_utf8()..];
        // A BASIC string (double quotes) processes escapes; a LITERAL string
        // (single quotes) does not, by TOML's definition. Both of these values
        // become filesystem paths, so the raw source text is the wrong thing to
        // build them from: the app's loader reads the DECODED value, and
        // `dir = "i18n\\bundles"` on Windows would otherwise have the generator
        // writing to a directory with a literal double backslash in its name
        // while the runtime reads the single-backslash one.
        //
        // The terminator has to respect escapes for the same reason: a `\"` is
        // part of the value, so stopping at it would truncate the path.
        if quote == '"' {
            let mut end = None;
            let mut escaped = false;
            for (i, c) in rest.char_indices() {
                if escaped {
                    escaped = false;
                } else if c == '\\' {
                    escaped = true;
                } else if c == '"' {
                    end = Some(i);
                    break;
                }
            }
            decode_toml_escapes(&rest[..end?])
        } else {
            rest[..rest.find(quote)?].to_owned()
        }
    } else {
        // A bare value runs to the first comment marker or end of line.
        trimmed
            .split_once('#')
            .map_or(trimmed, |(before, _)| before)
            .trim_end()
            .to_owned()
    };
    (!value.is_empty()).then_some(value)
}

/// Split an inline table's body on the commas that separate its members.
///
/// Quote-aware: a comma inside a value belongs to the value. `dir =
/// "translations,v2"` is a legal directory name, and splitting through it
/// leaves `toml_scalar_value` with an unterminated string, which it discards —
/// so the generator would silently fall back to `i18n/` and write its keys
/// where the runtime never looks.
///
/// Escapes are honoured while scanning so a `\"` inside a basic string does not
/// end it. Literal (single-quoted) strings process no escapes, per TOML.
fn split_inline_members(body: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut current = String::new();
    let mut quote: Option<char> = None;
    let mut escaped = false;
    for c in body.chars() {
        match quote {
            Some(q) => {
                current.push(c);
                if escaped {
                    escaped = false;
                } else if c == '\\' && q == '"' {
                    escaped = true;
                } else if c == q {
                    quote = None;
                }
            }
            None if c == '"' || c == '\'' => {
                quote = Some(c);
                current.push(c);
            }
            None if c == ',' => out.push(std::mem::take(&mut current)),
            None => current.push(c),
        }
    }
    out.push(current);
    out
}

/// Render `value` as the contents of a Rust double-quoted string literal.
///
/// A configured `dir` is interpolated into generated Rust (`embed_locales!`),
/// and TOML happily carries characters that Rust's lexer reads as escapes: the
/// Windows-shaped `dir = 'translations\bundles'` would emit `\b`, which is not
/// a Rust escape at all, so the generated `main.rs` stops parsing — before any
/// embed build, and for a project that merely configured a directory.
fn rust_string_escape(value: &str) -> String {
    value.replace('\\', "\\\\").replace('"', "\\\"")
}

/// Decode the escape sequences TOML defines for a basic string.
///
/// An unknown or malformed escape is passed through verbatim rather than
/// rejected: this is a best-effort read of a file the app's own loader
/// validates properly, and a generator that refused to run over a `dir` it
/// could not decode would be worse than one that used the text as written.
fn decode_toml_escapes(src: &str) -> String {
    let mut out = String::with_capacity(src.len());
    let mut chars = src.chars();
    while let Some(c) = chars.next() {
        if c != '\\' {
            out.push(c);
            continue;
        }
        let Some(esc) = chars.next() else {
            out.push('\\');
            break;
        };
        match esc {
            'b' => out.push('\u{8}'),
            't' => out.push('\t'),
            'n' => out.push('\n'),
            'f' => out.push('\u{c}'),
            'r' => out.push('\r'),
            '"' => out.push('"'),
            '\\' => out.push('\\'),
            'u' | 'U' => {
                let width = if esc == 'u' { 4 } else { 8 };
                let digits: String = chars.clone().take(width).collect();
                if let Some(decoded) = u32::from_str_radix(&digits, 16)
                    .ok()
                    .filter(|_| digits.len() == width)
                    .and_then(char::from_u32)
                {
                    out.push(decoded);
                    for _ in 0..width {
                        chars.next();
                    }
                } else {
                    out.push('\\');
                    out.push(esc);
                }
            }
            other => {
                out.push('\\');
                out.push(other);
            }
        }
    }
    out
}

/// Whether `autumn.toml` already defines i18n configuration **in any of TOML's
/// spellings**, so a second definition must not be appended.
///
/// TOML expresses the same table three ways, and all three collide with an
/// appended `[i18n]`:
///
/// ```toml
/// [i18n]                                       # a table header
/// i18n = { default_locale = "fr" }             # an inline table
/// i18n.default_locale = "fr"                   # a dotted key
/// ```
///
/// Missing any of them is not cosmetic: the generator appends `[i18n]`, TOML
/// rejects the duplicate definition, and the application can no longer load its
/// configuration at all. A dotted `i18n.x` under some other table
/// (`[server]\ni18n.x = …`) is a different key entirely, so only top-level ones
/// count.
/// Whether `autumn.toml` defines i18n configuration.
///
/// Parsed with the real TOML parser, which is already a direct dependency of
/// this crate. The line scan below has been extended once per round for
/// another spelling TOML allows — `[i18n]`, `["i18n"]`, `i18n = { … }`,
/// `"i18n" = { … }`, `i18n.default_locale`, `"i18n".default_locale`, quoted
/// member keys, escaped values, commas inside quoted values — and each miss
/// had the generator append a SECOND `[i18n]` table, which makes the file
/// unparseable for the app that has to read it. Enumerating token classes by
/// hand does not converge; `toml::Table` knows them all.
///
/// The scan survives as the fallback for a file that does not parse. That is
/// deliberate and predates this: a malformed `autumn.toml` should not fail
/// generation here, because the app's own loader reports it far better.
fn defines_i18n(autumn_toml: &str) -> bool {
    autumn_toml.parse::<toml::Table>().map_or_else(
        |_| defines_i18n_by_scan(autumn_toml),
        |table| table.contains_key("i18n"),
    )
}

/// What an existing `autumn.toml` configures for i18n, as
/// `(default_locale, dir)`.
///
/// Structural for the same reason as [`defines_i18n`], and with the same
/// fallback. Reading these from the source text rather than the parsed value
/// is what sent generated keys to `i18n/en.ftl` while the runtime loaded
/// `translations/fr.ftl`.
pub(super) fn configured_i18n(autumn_toml: &str) -> (Option<String>, Option<String>) {
    let Ok(table) = autumn_toml.parse::<toml::Table>() else {
        return configured_i18n_by_scan(autumn_toml);
    };
    let i18n = table.get("i18n");
    let member = |key: &str| {
        i18n.and_then(|v| v.get(key))
            .and_then(toml::Value::as_str)
            .map(str::to_owned)
    };
    (member("default_locale"), member("dir"))
}

fn defines_i18n_by_scan(autumn_toml: &str) -> bool {
    let mut at_top_level = true;
    for line in autumn_toml.lines() {
        if let Some(name) = toml_table_name(line) {
            if name == "i18n" {
                return true;
            }
            at_top_level = false;
            continue;
        }
        if !at_top_level {
            continue;
        }
        let trimmed = line.trim();
        if let Some((key, _)) = trimmed.split_once('=') {
            let key = key.trim();
            if key == "i18n" || key.starts_with("i18n.") {
                return true;
            }
        }
    }
    false
}

/// What an existing `autumn.toml` configures for i18n: the default locale, and
/// the directory its bundles live in.
///
/// Both matter for where the generated keys go. The runtime resolves lookups
/// through `<dir>/<default_locale>.ftl`, so writing to a hardcoded
/// `i18n/en.ftl` in a project configured otherwise leaves the app's real bundle
/// without a single generated key: every label renders as a visible `{$key}`
/// placeholder, and `autumn i18n check` reports them all missing — while `t!`'s
/// compile-time validation (which looks under `i18n/` for `en` by default)
/// passes, so nothing catches it until runtime.
///
/// Deliberately a line scan rather than a TOML parse: this needs two keys, the
/// file may carry profile overlays the generator has no business interpreting,
/// and a malformed `autumn.toml` should not fail generation here — the app's own
/// loader reports that far better. `[profile.<env>.i18n]` overlays are ignored:
/// the generator writes the base bundle, which every profile inherits.
fn configured_i18n_by_scan(autumn_toml: &str) -> (Option<String>, Option<String>) {
    let mut in_i18n = false;
    let mut at_top_level = true;
    let (mut locale, mut dir) = (None, None);
    for line in autumn_toml.lines() {
        if let Some(name) = toml_table_name(line) {
            in_i18n = name == "i18n";
            at_top_level = false;
            continue;
        }
        let trimmed = line.trim();
        let Some((raw_key, value)) = trimmed.split_once('=') else {
            continue;
        };
        // Dotted keys (`i18n.default_locale = "fr"`) carry the table in the key
        // itself, so they are read at top level rather than inside `[i18n]`.
        let (key, value) = if in_i18n {
            (raw_key, value)
        } else if at_top_level {
            match raw_key.trim().strip_prefix("i18n.") {
                Some(rest) => (rest, value),
                // An inline `i18n = { default_locale = "fr", … }`: read the
                // members out of the braces.
                None if raw_key.trim() == "i18n" => {
                    for member in
                        split_inline_members(value.trim().trim_matches(|c| c == '{' || c == '}'))
                    {
                        let member = member.as_str();
                        let Some((k, v)) = member.split_once('=') else {
                            continue;
                        };
                        let Some(v) = toml_scalar_value(v) else {
                            continue;
                        };
                        match toml_key_name(k) {
                            "default_locale" => locale = Some(v.clone()),
                            "dir" => dir = Some(v.clone()),
                            _ => {}
                        }
                    }
                    continue;
                }
                None => continue,
            }
        } else {
            continue;
        };
        let Some(value) = toml_scalar_value(value) else {
            continue;
        };
        match toml_key_name(key) {
            "default_locale" => locale = Some(value.clone()),
            "dir" => dir = Some(value.clone()),
            _ => {}
        }
    }
    (locale, dir)
}

/// The two environment variables `t!`'s compile-time key check reads, as the
/// COMPILER will see them.
///
/// `t!` does not read `autumn.toml`. It resolves its validation bundle from
/// `AUTUMN_I18N_FILE`, else `$CARGO_MANIFEST_DIR/i18n/$AUTUMN_I18N_DEFAULT_LOCALE.ftl`
/// with the locale defaulting to `en` (`autumn-macros/src/i18n.rs`), and
/// degrades to a runtime lookup when neither exists. A generator that assumes
/// `i18n/en.ftl` keeps the wrong file in step: with the locale set to `fr` the
/// validator reads `i18n/fr.ftl`, which then lacks every key just generated,
/// and `cargo check` fails with a `compile_error!` per lookup.
#[derive(Debug, Default, PartialEq, Eq)]
pub(super) struct MacroEnv {
    pub(super) file: Option<String>,
    pub(super) default_locale: Option<String>,
}

impl MacroEnv {
    /// The process environment, with the project's own `.cargo/config.toml`
    /// `[env]` table layered underneath — which is where a setting the macro
    /// needs on EVERY build realistically lives, and which this process does
    /// not otherwise inherit.
    ///
    /// Only the project's own config is read. Ancestor directories and
    /// `$CARGO_HOME` can also carry one, but those are outside the tree being
    /// generated into and nothing here can see which of them cargo would pick.
    pub(super) fn resolve(project_root: &Path) -> Self {
        let config = ["config.toml", "config"]
            .into_iter()
            .find_map(|name| std::fs::read_to_string(project_root.join(".cargo").join(name)).ok())
            .unwrap_or_default();
        let configured = cargo_config_env(&config, project_root);
        let read = |name: &str| layer_cargo_env(configured.get(name), std::env::var(name).ok());
        Self {
            file: read("AUTUMN_I18N_FILE"),
            default_locale: read("AUTUMN_I18N_DEFAULT_LOCALE"),
        }
    }
}

/// One variable's value as cargo would set it: a config entry applies only when
/// the process does not already carry the variable, unless the entry asks to
/// `force`.
fn layer_cargo_env(
    configured: Option<&(String, bool)>,
    from_process: Option<String>,
) -> Option<String> {
    match configured {
        Some((value, force)) if *force || from_process.is_none() => Some(value.clone()),
        _ => from_process,
    }
}

/// The `[env]` table of a `.cargo/config.toml`, as `name -> (value, force)`.
///
/// An entry is either a bare string or a table carrying `value` plus the
/// optional `force` and `relative` flags; `relative` makes the value a path
/// resolved against the directory holding `.cargo`, which is what cargo itself
/// does.
fn cargo_config_env(config: &str, project_root: &Path) -> BTreeMap<String, (String, bool)> {
    let Ok(table) = config.parse::<toml::Table>() else {
        return BTreeMap::new();
    };
    let Some(env) = table.get("env").and_then(toml::Value::as_table) else {
        return BTreeMap::new();
    };
    env.iter()
        .filter_map(|(name, entry)| {
            let (value, force, relative) = match entry {
                toml::Value::String(value) => (value.clone(), false, false),
                toml::Value::Table(fields) => (
                    fields.get("value")?.as_str()?.to_owned(),
                    fields.get("force").and_then(toml::Value::as_bool) == Some(true),
                    fields.get("relative").and_then(toml::Value::as_bool) == Some(true),
                ),
                _ => return None,
            };
            let value = if relative {
                project_root.join(value).to_string_lossy().into_owned()
            } else {
                value
            };
            Some((name.clone(), (value, force)))
        })
        .collect()
}

/// The bundle `t!` will validate against, or `None` when the macro would find
/// none and fall back to a runtime lookup.
///
/// Mirrors `locate_default_bundle` in `autumn-macros/src/i18n.rs`, including
/// its requirement that the file EXIST: an absent bundle means there is no
/// compile-time check to keep in step, and writing one would invent a locale
/// the project deliberately does not have.
pub(super) fn validator_bundle_path(project_root: &Path, env: &MacroEnv) -> Option<PathBuf> {
    if let Some(file) = &env.file {
        // A relative `AUTUMN_I18N_FILE` is resolved by the compiler against its
        // own working directory, which for a cargo build is the workspace root.
        // The project root is that directory for a generated app.
        let path = project_root.join(file);
        return path.is_file().then_some(path);
    }
    let locale = env.default_locale.as_deref().unwrap_or("en");
    let path = project_root.join("i18n").join(format!("{locale}.ftl"));
    path.is_file().then_some(path)
}

/// The `static` item `autumn new` emits for embedded assets — where the locale
/// static is written next to.
const STATIC_ANCHOR: &str =
    "static EMBEDDED_STATIC: autumn_web::include_dir::Dir = autumn_web::embed_static!();";
/// The builder line that installs those assets — where the locale install goes.
const INSTALL_ANCHOR: &str = "    let app = app.embedded_static(&EMBEDDED_STATIC);\n";

/// Embed the locale bundle into the binary for `autumn build --embed`,
/// matching what `autumn new --with-i18n` wires into a fresh app.
///
/// `.i18n_auto()` alone loads from DISK. An `--embed` build is supposed to be
/// self-contained, so without this the binary still reaches for the locale
/// directory at startup: run it from an empty deployment directory — or from
/// the release image, whose embedded-build path deliberately ships no sidecar —
/// and it panics on a missing default bundle, after a build that looked
/// entirely clean.
///
/// Both edits sit behind the `embed-assets` feature the template already gates
/// its static assets on, and both anchor on the `EMBEDDED_STATIC` lines that
/// `autumn new` emits. Returns `None` when those are absent (an `--api` or
/// hand-rolled `main.rs`), so the caller can leave it alone; returns the input
/// unchanged when the locales are already embedded.
pub(super) fn ensure_embedded_locales(main_rs: &str, dir: &str) -> Option<String> {
    // `embed_locales!()` defaults to `i18n/`; a configured directory is passed
    // through as the macro's literal argument — escaped, because this is the one
    // place a `dir` read out of `autumn.toml` becomes Rust source.
    let macro_call = if dir == "i18n" {
        "autumn_web::embed_locales!()".to_owned()
    } else {
        format!(
            "autumn_web::embed_locales!(\"{}\")",
            rust_string_escape(dir)
        )
    };
    // PRODUCTION occurrences only. A `#[cfg(test)]` fixture that happens to
    // mention `EMBEDDED_LOCALES` is not the binary's embedding, and treating it
    // as one returns "already wired" while `autumn build --embed` ships a
    // release binary with no bundle in it — which panics on a machine that has
    // no sidecar locale directory. Same scoping `ensure_i18n_auto` applies to
    // its own detections; it belongs here for the same reason.
    // As a WHOLE identifier. A substring match reads an unrelated
    // `ADMIN_EMBEDDED_LOCALES` as this static, reports the file as already
    // embedded, and then hands the install below a symbol the file never
    // declares — an `--embed` build that stops compiling on an undefined name.
    let embedded_in_production = identifier_offsets(main_rs, "EMBEDDED_LOCALES")
        .into_iter()
        .any(|at| !in_cfg_test(main_rs, at));
    // The static ALONE is not the setup. `embed_locales!` bakes the files into
    // the binary; `.embedded_locales(&EMBEDDED_LOCALES)` is what makes the app
    // read them. With the first present and the second missing, an
    // `autumn build --embed` carries the bundle and never loads it — so a
    // deployment without the sidecar directory falls through to `.i18n_auto()`
    // and panics, having been told embedding was configured. Both halves are
    // required before this is treated as done, and a missing half is added.
    // Scoped to the function the PRODUCTION builder lives in, not merely to
    // "outside `cfg(test)`". A preview or helper builder is ordinary
    // non-test code, and one of those installing the locales says nothing
    // about the chain the binary runs: treating it as done leaves production
    // falling through to `.i18n_auto()`, so an `--embed` deployment without the
    // sidecar directory panics with the static sitting unused in the binary.
    let scopes = production_scopes(main_rs);
    let installed_in_production = method_call_offsets(main_rs, ".embedded_locales")
        .any(|at| in_production(main_rs, &scopes, at));

    if embedded_in_production {
        // Already embedded — but not necessarily from the right place. A
        // project that changed `[i18n] dir` after its first `--i18n` scaffold
        // keeps embedding the OLD directory while the keys, the Docker `COPY`,
        // and the runtime load all move to the new one, so an `--embed` build
        // ships a bundle the app never reads. Repoint it.
        //
        // Within THIS static's own item, not anywhere in the file. A `main.rs`
        // can carry more than one embedded directory — an `ADMIN_EMBEDDED_LOCALES`
        // beside this one is ordinary — and rewriting whichever `embed_locales!`
        // came first repoints somebody else's bundle at this resource's
        // directory: the admin app then ships the wrong translations, and the
        // static this call is actually about keeps its stale directory.
        //
        // No declaration found (a hand-rolled or macro-generated static), or no
        // `embed_locales!` in it: the macro is left alone, and only the install
        // below is checked.
        let stale_macro = locales_static_item(main_rs).and_then(|(start, end)| {
            let item = &main_rs[start..end];
            if !real_offsets(item, &macro_call).is_empty() {
                return None;
            }
            let rel = real_offsets(item, "autumn_web::embed_locales!")
                .first()
                .copied()?;
            Some((start + rel, end))
        });
        let mut out = match stale_macro {
            Some((call_at, end)) => {
                format!("{}{macro_call}{}", &main_rs[..call_at], &main_rs[end..])
            }
            None => main_rs.to_owned(),
        };
        if !installed_in_production {
            out = insert_locale_install(&out)?;
        }
        return Some(out);
    }
    if !main_rs.contains(STATIC_ANCHOR) {
        return None;
    }
    let with_static = main_rs.replacen(
        STATIC_ANCHOR,
        &format!(
            "{STATIC_ANCHOR}\n#[cfg(feature = \"embed-assets\")]\n\
             static EMBEDDED_LOCALES: autumn_web::include_dir::Dir = {macro_call};"
        ),
        1,
    );
    insert_locale_install(&with_static)
}

/// Splice `.embedded_locales(&EMBEDDED_LOCALES)` in after the PRODUCTION
/// `embedded_static` install, or `None` when there is no such line.
///
/// The anchor is picked with the same production test that decided the install
/// was missing in the first place, because the two questions have to be asked
/// about the same code. A file-wide "first occurrence" replacement answered
/// them at different granularities: with a preview or helper builder above
/// `main` carrying the ordinary `let app = app.embedded_static(&EMBEDDED_STATIC);`
/// line, the detection correctly reported production as missing the call and
/// the insertion then wrote it into the HELPER — leaving the production
/// `--embed` binary still falling through to a disk load, which panics when the
/// deployment has no sidecar locale directory. Recomputed against the text
/// passed in, since an earlier edit may have shifted every offset.
fn insert_locale_install(src: &str) -> Option<String> {
    let scopes = production_scopes(src);
    let at = real_offsets(src, INSTALL_ANCHOR)
        .into_iter()
        .find(|&at| in_production(src, &scopes, at))?;
    let end = at + INSTALL_ANCHOR.len();
    Some(format!(
        "{}{INSTALL_ANCHOR}    #[cfg(feature = \"embed-assets\")]\n\
         \x20   let app = app.embedded_locales(&EMBEDDED_LOCALES);\n{}",
        &src[..at],
        &src[end..]
    ))
}

/// The function bodies holding the builders the binary runs.
fn production_scopes(src: &str) -> Vec<(usize, usize)> {
    production_routes_anchors(src)
        .into_iter()
        .filter_map(|at| enclosing_body(src, at))
        .collect()
}

/// Whether `at` sits in one of `scopes` — or, when no production builder could
/// be identified at all, merely outside `#[cfg(test)]`.
///
/// The fallback is the coarser question, taken deliberately: with nothing to
/// scope to, "anything non-test" is a better read than "nothing counts".
fn in_production(src: &str, scopes: &[(usize, usize)], at: usize) -> bool {
    if scopes.is_empty() {
        !in_cfg_test(src, at)
    } else {
        scopes.iter().any(|&(open, close)| open < at && at < close)
    }
}

/// Ship the `i18n/` sidecar into a generated `Dockerfile`, in both stages.
///
/// `.i18n_auto()` reads `i18n/<default>.ftl` from the working directory at
/// startup and **panics** when it is missing (`autumn/src/app.rs`'s
/// `resolve_i18n_bundle`). `autumn new --with-i18n` handles this by resolving
/// the Dockerfile's i18n anchors; a plain `autumn new` strips them, so a project
/// that adopts `--i18n` later builds an image with no bundle in it and
/// crash-loops on deploy — after a build that looked completely clean, because
/// `t!`'s compile-time key check silently degrades to a runtime lookup when the
/// file is absent from the build context.
///
/// The two `COPY` lines are inserted next to the ones for `migrations/`, which
/// both stages already carry and which sit at exactly the same layer. Returns
/// `None` when the file has no such anchor (a hand-edited or absent Dockerfile),
/// so the caller can warn instead of guessing where to write.
pub(super) fn ensure_dockerfile_i18n_copy(dockerfile: &str, dir: &str) -> Option<String> {
    let builder_anchor = "COPY migrations ./migrations";
    let runtime_anchor = "COPY --from=builder /app/migrations /app/migrations";
    // A `dir` carrying whitespace is a legal path, and the shell form splits on
    // it: `COPY translations v2 ./translations v2` reads as three sources and a
    // destination, so the build either fails or copies the wrong thing. The
    // JSON form is exactly what Docker documents for paths with spaces. Used
    // only when needed, so the ordinary Dockerfile keeps its conventional
    // shell-form lines.
    let (builder_line, runtime_line) = if dir.contains(char::is_whitespace) {
        (
            format!(
                "COPY [{}, {}]",
                json_str(dir),
                json_str(&format!("./{dir}"))
            ),
            format!(
                "COPY --from=builder [{}, {}]",
                json_str(&format!("/app/{dir}")),
                json_str(&format!("/app/{dir}"))
            ),
        )
    } else {
        (
            format!("COPY {dir} ./{dir}"),
            format!("COPY --from=builder /app/{dir} /app/{dir}"),
        )
    };
    if dockerfile.contains(&builder_line) && dockerfile.contains(&runtime_line) {
        return Some(dockerfile.to_owned());
    }
    if !dockerfile.contains(builder_anchor) || !dockerfile.contains(runtime_anchor) {
        return None;
    }
    // Runtime stage first: its anchor is a superstring-free, later occurrence,
    // and replacing the builder anchor first would shift it.
    let out = dockerfile.replacen(
        runtime_anchor,
        &format!("{runtime_anchor}\n{runtime_line}"),
        1,
    );
    Some(out.replacen(
        builder_anchor,
        &format!("{builder_anchor}\n{builder_line}"),
        1,
    ))
}

/// The directory an earlier `--i18n` run pointed the Dockerfile's locale
/// `COPY` lines at, when that is no longer the configured `dir`.
///
/// A project that changes `[i18n] dir` after its first `--i18n` scaffold keeps
/// the old pair, and `ensure_dockerfile_i18n_copy` adds a second one for the
/// new directory. That is worth saying out loud: `COPY` fails the build when
/// its source is missing from the context, so a rename that MOVED the old
/// directory stops the image building at all, and one that merely copied it
/// ships a bundle the app never reads.
///
/// Reported rather than rewritten. These lines carry no marker, so "the
/// generator wrote this" can only ever be inferred — and the inference is a
/// shape (`COPY <x> ./<x>`) that an ordinary hand-written `COPY static
/// ./static` matches exactly. A warning that occasionally names the wrong
/// directory costs the reader a second; an edit that silently rewrites
/// someone's asset `COPY` into a locale one costs them their image. So the
/// position is used as corroboration (this generator inserts immediately after
/// the `migrations` anchors) and the result is still only ever advice.
pub(super) fn stale_dockerfile_i18n_dir(dockerfile: &str, dir: &str) -> Option<String> {
    /// The `[src, dest]` of a `COPY`, in EITHER form.
    ///
    /// The JSON form is not optional to support: this generator emits it itself
    /// for a `dir` containing whitespace, so a detector that only splits on
    /// spaces cannot see the very lines it wrote — leaving the stale pair
    /// unreported for exactly the paths that most need quoting.
    fn copy_operands(line: &str, from_builder: bool) -> Option<(String, String)> {
        let rest = line.trim().strip_prefix("COPY ")?.trim_start();
        let rest = if from_builder {
            rest.strip_prefix("--from=builder")?.trim_start()
        } else {
            if rest.starts_with("--") {
                return None;
            }
            rest
        };
        if let Some(inner) = rest.strip_prefix('[').and_then(|r| r.strip_suffix(']')) {
            let mut parts = inner.split(',').map(|p| {
                p.trim()
                    .trim_matches('"')
                    .replace("\\\"", "\"")
                    .replace("\\\\", "\\")
            });
            return Some((parts.next()?, parts.next()?));
        }
        let parts: Vec<&str> = rest.split_whitespace().collect();
        match parts.as_slice() {
            [src, dest] => Some(((*src).to_owned(), (*dest).to_owned())),
            _ => None,
        }
    }
    /// The directory in `COPY <x> ./<x>`, in either form.
    fn builder_copy_dir(line: &str) -> Option<String> {
        let (src, dest) = copy_operands(line, false)?;
        (dest.strip_prefix("./") == Some(src.as_str())).then_some(src)
    }
    /// The same for `COPY --from=builder /app/<x> /app/<x>`.
    fn runtime_copy_dir(line: &str) -> Option<String> {
        let (src, dest) = copy_operands(line, true)?;
        if src != dest {
            return None;
        }
        src.strip_prefix("/app/")
            .filter(|d| !d.contains('/'))
            .map(str::to_owned)
    }

    let after = |anchor: &str, extract: fn(&str) -> Option<String>| -> Option<String> {
        let mut lines = dockerfile.lines().skip_while(|l| l.trim() != anchor);
        lines.next()?;
        extract(lines.next()?)
    };

    let builder = after("COPY migrations ./migrations", builder_copy_dir)?;
    let runtime = after(
        "COPY --from=builder /app/migrations /app/migrations",
        runtime_copy_dir,
    )?;
    // Both stages naming the same non-configured directory is what makes this a
    // moved bundle rather than a coincidence.
    (builder == runtime && builder != dir).then_some(builder)
}

/// Profile overlays that point i18n somewhere other than the base config.
///
/// `[profile.prod.i18n]` (and the sibling `autumn-<env>.toml` files) can
/// override `dir` and `default_locale`, and the runtime resolves the FULLY
/// LAYERED config — so a base of `i18n/en.ftl` with a production override of
/// `dir = "translations"` means the image ships `i18n/` while the app boots
/// looking for `translations/`, and `.i18n_auto()` panics.
///
/// The generator deliberately writes the BASE bundle only. Writing English into
/// a profile that exists precisely because it serves a different locale would
/// be its own bug, and there is no way to know which profile a given deploy
/// uses — so this reports the overlays instead, and the caller warns. Returns
/// the `(profile, dir/locale summary)` pairs that differ from the base.
/// The same report for a STANDALONE `autumn-<profile>.toml`, whose `[i18n]`
/// sits at top level rather than under `[profile.<env>.i18n]`.
///
/// These are a separate layer, not a spelling variant: the runtime merges
/// `autumn-{profile}.toml` LAST, after both `autumn.toml` and its inline
/// `[profile.…]` sections (`autumn/src/config.rs`). A project keeping its
/// production config in one of these gets no `[profile.prod.i18n]` for
/// [`profile_i18n_overrides`] to find, so scanning only the base file reports
/// nothing at all — and the deploy that matters is exactly the one pointed
/// somewhere this scaffold never wrote.
///
/// `files` is `(profile name, file contents)`; returns `(profile, path)` for
/// those whose i18n differs from the base.
pub(super) fn profile_file_i18n_overrides(
    files: &[(String, String)],
    base_dir: &str,
    base_locale: &str,
) -> Vec<(String, String)> {
    let mut out = Vec::new();
    for (profile, contents) in files {
        let (locale, dir) = configured_i18n(contents);
        let differs = dir.as_deref().is_some_and(|d| d != base_dir)
            || locale.as_deref().is_some_and(|l| l != base_locale);
        if !differs {
            continue;
        }
        out.push((
            profile.clone(),
            format!(
                "{}/{}.ftl",
                dir.as_deref().unwrap_or(base_dir),
                locale.as_deref().unwrap_or(base_locale)
            ),
        ));
    }
    out
}

pub(super) fn profile_i18n_overrides(
    autumn_toml: &str,
    base_dir: &str,
    base_locale: &str,
) -> Vec<(String, String)> {
    // Structural when the file parses, for the same reason `configured_i18n` is
    // — and this is the half of that change I left undone last round, which
    // produced a finding immediately. `[profile.prod.i18n]` is only ONE of the
    // spellings the runtime merges: `[profile.prod]` with `i18n = { … }`, a
    // dotted `profile.prod.i18n.dir`, and any of them quoted all reach the same
    // table, and a scan keyed on a header ending in `.i18n` sees none of them.
    // Missing one means no warning for a production deploy pointed at a bundle
    // this scaffold never wrote — which is a startup panic, not a cosmetic gap.
    if let Ok(table) = autumn_toml.parse::<toml::Table>() {
        let mut out = Vec::new();
        let profiles = table.get("profile").and_then(toml::Value::as_table);
        for (profile, value) in profiles.into_iter().flatten() {
            let Some(i18n) = value.get("i18n") else {
                continue;
            };
            let member = |key: &str| i18n.get(key).and_then(toml::Value::as_str);
            let (dir, locale) = (member("dir"), member("default_locale"));
            let differs =
                dir.is_some_and(|d| d != base_dir) || locale.is_some_and(|l| l != base_locale);
            if !differs {
                continue;
            }
            out.push((
                profile.clone(),
                format!(
                    "{}/{}.ftl",
                    dir.unwrap_or(base_dir),
                    locale.unwrap_or(base_locale)
                ),
            ));
        }
        out.sort();
        return out;
    }
    profile_i18n_overrides_by_scan(autumn_toml, base_dir, base_locale)
}

fn profile_i18n_overrides_by_scan(
    autumn_toml: &str,
    base_dir: &str,
    base_locale: &str,
) -> Vec<(String, String)> {
    let mut out = Vec::new();
    let mut current: Option<String> = None;
    let (mut dir, mut locale) = (None, None);
    let mut flush = |profile: Option<String>, dir: Option<String>, locale: Option<String>| {
        let Some(profile) = profile else { return };
        let differs = dir.as_deref().is_some_and(|d| d != base_dir)
            || locale.as_deref().is_some_and(|l| l != base_locale);
        if !differs {
            return;
        }
        let path = format!(
            "{}/{}.ftl",
            dir.as_deref().unwrap_or(base_dir),
            locale.as_deref().unwrap_or(base_locale)
        );
        out.push((profile, path));
    };
    for line in autumn_toml.lines() {
        if let Some(name) = toml_table_name(line) {
            flush(current.take(), dir.take(), locale.take());
            // `[profile.<env>.i18n]`
            current = name
                .strip_prefix("profile.")
                .and_then(|rest| rest.strip_suffix(".i18n"))
                .map(str::to_owned);
            continue;
        }
        if current.is_none() {
            continue;
        }
        let trimmed = line.trim();
        let Some((key, value)) = trimmed.split_once('=') else {
            continue;
        };
        let Some(value) = toml_scalar_value(value) else {
            continue;
        };
        match toml_key_name(key) {
            "default_locale" => locale = Some(value.clone()),
            "dir" => dir = Some(value.clone()),
            _ => {}
        }
    }
    flush(current, dir, locale);
    out
}

/// Add an `[i18n]` block to `autumn.toml` if it has none.
///
/// `default_locale = "en"` matches the `en.ftl` the generator writes; the
/// supported list starts as `["en"]` so an app that adds `fr.ftl` only has to
/// extend one line. A project that already configures `[i18n]` is left alone —
/// its `default_locale` may not be `en`, and rewriting it would silently
/// repoint the bundle the app loads.
pub(super) fn ensure_i18n_config_block(existing: &str) -> String {
    // Match the CONFIGURATION, not the literal text — see `defines_i18n`.
    if defines_i18n(existing) {
        return existing.to_owned();
    }
    let mut out = existing.to_owned();
    if !out.is_empty() && !out.ends_with('\n') {
        out.push('\n');
    }
    if !out.is_empty() {
        out.push('\n');
    }
    out.push_str("[i18n]\ndefault_locale = \"en\"\nsupported_locales = [\"en\"]\n");
    out
}

/// Byte offsets of every `needle` in `src` that is REAL CODE — not inside a
/// line comment, a (nestable) block comment, a string or raw-string literal, or
/// a char literal.
///
/// `autumn new`'s own template carries the line
/// `// Register new endpoints by adding them to the .routes(routes![...]) list`
/// right above `fn main`, and a naive `find(".routes(")` lands there: the
/// `.i18n_auto()` call gets written into a COMMENT, the builder chain is never
/// touched, and the idempotency guard then makes every later run a no-op. The
/// app compiles, starts, and renders raw keys forever with no error anywhere.
/// Same class of decoy — and the same lexical defence — as
/// [`has_shared_layout`](super::scaffold::has_shared_layout).
pub(super) fn real_offsets(src: &str, needle: &str) -> Vec<usize> {
    let bytes = src.as_bytes();
    let n = needle.as_bytes();
    let mut out = Vec::new();
    let mut i = 0usize;
    let mut block_depth = 0usize;
    while i < bytes.len() {
        if block_depth > 0 {
            if bytes[i..].starts_with(b"/*") {
                block_depth += 1;
                i += 2;
            } else if bytes[i..].starts_with(b"*/") {
                block_depth -= 1;
                i += 2;
            } else {
                i += 1;
            }
            continue;
        }
        if bytes[i..].starts_with(b"//") {
            i += src[i..].find('\n').map_or(src.len() - i, |nl| nl + 1);
            continue;
        }
        if bytes[i..].starts_with(b"/*") {
            block_depth = 1;
            i += 2;
            continue;
        }
        if is_raw_string_start(bytes, i) {
            i = skip_raw_string(bytes, i);
            continue;
        }
        if bytes[i] == b'"' {
            i += 1;
            while i < bytes.len() && bytes[i] != b'"' {
                i += usize::from(bytes[i] == b'\\') + 1;
            }
            i += 1;
            continue;
        }
        // A CHAR literal, which the doc above has always claimed and the code
        // did not do. `let open = '{';` is the case that bites: its brace is
        // counted as syntax, so `brace_block` never finds where `main` ends and
        // the anchor search falls back to whatever builder comes first. `'"'`
        // is worse — it opens a phantom string that swallows the rest of the
        // file. Distinguished from a LIFETIME (`&'a str`) by looking for the
        // closing quote: `'a` has none, `'{'` does.
        if bytes[i] == b'\'' {
            if let Some(end) = char_literal_end(bytes, i) {
                i = end + 1;
                continue;
            }
            // A lifetime. Step past the tick only, so `'a` does not eat ahead.
            i += 1;
            continue;
        }
        if bytes[i..].starts_with(n) {
            out.push(i);
            i += n.len();
            continue;
        }
        i += 1;
    }
    out
}

/// `value` as a JSON string literal, for Dockerfile's exec/JSON `COPY` form.
fn json_str(value: &str) -> String {
    format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
}

/// Offsets of `name` in real code where it is a WHOLE identifier, not a slice
/// of a longer one.
///
/// The same token-boundary rule [`method_call_offsets`] applies to method
/// names, for the identifiers this module looks up by name.
fn identifier_offsets(src: &str, name: &str) -> Vec<usize> {
    let ident_char = |c: char| c.is_alphanumeric() || c == '_';
    real_offsets(src, name)
        .into_iter()
        .filter(|&at| {
            !src[..at].chars().next_back().is_some_and(ident_char)
                && !src[at + name.len()..]
                    .chars()
                    .next()
                    .is_some_and(ident_char)
        })
        .collect()
}

/// The production `static EMBEDDED_LOCALES … ;` declaration, as the span from
/// its name to its terminating `;`.
///
/// A DECLARATION, told from a use site (`.embedded_locales(&EMBEDDED_LOCALES)`)
/// by the `static` keyword in front of it, so the repointing above rewrites the
/// initialiser rather than something that merely mentions the name.
fn locales_static_item(src: &str) -> Option<(usize, usize)> {
    identifier_offsets(src, "EMBEDDED_LOCALES")
        .into_iter()
        .filter(|&at| !in_cfg_test(src, at))
        .find_map(|at| {
            let before = src[..at].trim_end();
            let keyword = before.strip_suffix("static")?;
            // On an identifier boundary of its own: `mystatic EMBEDDED_LOCALES`
            // is not a static declaration.
            if keyword
                .chars()
                .next_back()
                .is_some_and(|c| c.is_alphanumeric() || c == '_')
            {
                return None;
            }
            let semi = real_offsets(&src[at..], ";").first().copied()?;
            Some((at, at + semi))
        })
}

/// Offsets of real-code `method` calls, tolerating whitespace and comments
/// between the method name and its opening paren, and requiring the name to end
/// on a token boundary so `.i18n` does not match `.i18n_auto`.
fn method_call_offsets<'a>(src: &'a str, method: &'a str) -> impl Iterator<Item = usize> + 'a {
    real_offsets(src, method).into_iter().filter(move |&at| {
        let rest = &src[at + method.len()..];
        // `.i18n_auto(` is a different method that starts with this name.
        if rest
            .chars()
            .next()
            .is_some_and(|c| c.is_alphanumeric() || c == '_')
        {
            return false;
        }
        // Only whitespace and comments may sit before the paren. `real_offsets`
        // over the remainder is the cheapest way to say "the next real token".
        real_offsets(rest, "(").first() == Some(&ignorable_prefix_len(rest))
    })
}

/// Length of the run of whitespace and comments at the start of `src`.
///
/// Block comments NEST in Rust, and this has to agree with [`real_offsets`]
/// about where one ends, because [`method_call_offsets`] compares the two: the
/// first `*/` in `.i18n /* outer /* nested */ tail */ (bundle())` closes only
/// the inner comment, and stopping there put this length short of the paren
/// `real_offsets` reports. The two disagreed, the call was not recognised as a
/// call, and `.i18n_auto()` went in and CLEARED the bundle that comment was
/// sitting next to.
pub(super) fn ignorable_prefix_len(src: &str) -> usize {
    let bytes = src.as_bytes();
    let mut i = 0;
    loop {
        let rest = &src[i..];
        let trimmed = rest.trim_start();
        i += rest.len() - trimmed.len();
        if let Some(after) = src[i..].strip_prefix("//") {
            i += 2 + after.find('\n').map_or(after.len(), |nl| nl + 1);
            continue;
        }
        if src[i..].starts_with("/*") {
            let mut depth = 1usize;
            i += 2;
            while i < bytes.len() && depth > 0 {
                if bytes[i..].starts_with(b"/*") {
                    depth += 1;
                    i += 2;
                } else if bytes[i..].starts_with(b"*/") {
                    depth -= 1;
                    i += 2;
                } else {
                    i += 1;
                }
            }
            continue;
        }
        return i;
    }
}

/// Byte offset of a char literal's closing `'`, when `at` opens one.
///
/// `None` for a lifetime (`&'a str`, `'static`), which shares the opening
/// character and must not be treated as a literal — skipping to a later `'`
/// would swallow real code between them.
fn char_literal_end(bytes: &[u8], at: usize) -> Option<usize> {
    let mut i = at + 1;
    if bytes.get(i)? == &b'\\' {
        // An escape. Skip the ESCAPED character before looking for the closing
        // tick — `'\''` carries a tick of its own, and stopping at it would cut
        // the literal one byte short and leave the real closing tick to open a
        // phantom one.
        i += 1;
        let selector = *bytes.get(i)?;
        i += 1;
        match selector {
            // `\u{1F600}` — variable length, delimited by its own brace.
            b'u' => {
                while bytes.get(i).is_some_and(|b| *b != b'}') {
                    i += 1;
                }
                i += 1;
            }
            // `\x41` — exactly two hex digits.
            b'x' => i += 2,
            // `\n`, `\t`, `\\`, `\'`, `\"`, `\0` — the selector was the whole
            // escape.
            _ => {}
        }
        return (bytes.get(i) == Some(&b'\'')).then_some(i);
    }
    // One character, which may be multi-byte UTF-8; the closing tick is the
    // next ASCII `'` within four bytes.
    let limit = (i + 4).min(bytes.len());
    while i < limit {
        if bytes[i] == b'\'' {
            return Some(i);
        }
        i += 1;
    }
    None
}

/// The `(open, close)` byte offsets of the first brace-delimited block at or
/// after `from` — the body of the item declared there.
///
/// Brace-matched, and blind to braces inside comments and string literals for
/// the same reason [`real_offsets`] is: a `//` line mentioning `}` would
/// otherwise close the body early and shrink the window this bounds a search
/// to. `None` when there is no `{`, or when it is never closed.
fn brace_block(src: &str, from: usize) -> Option<(usize, usize)> {
    // `real_offsets` gives brace positions that are real code; the first one at
    // or after `from` opens the body.
    let open = real_offsets(&src[from..], "{").first().copied()? + from;
    let tail = &src[open..];
    let mut braces: Vec<(usize, bool)> = real_offsets(tail, "{")
        .into_iter()
        .map(|o| (o, true))
        .chain(real_offsets(tail, "}").into_iter().map(|o| (o, false)))
        .collect();
    braces.sort_unstable();

    let mut depth = 0usize;
    for (at, is_open) in braces {
        if is_open {
            depth += 1;
        } else {
            depth = depth.checked_sub(1)?;
            if depth == 0 {
                return Some((open, open + at));
            }
        }
    }
    None
}

/// The outcome of trying to wire `.i18n_auto()` into `main.rs`.
#[derive(Debug, PartialEq, Eq)]
pub(super) enum I18nAutoWiring {
    /// The builder chain now calls `.i18n_auto()` (or already did).
    Wired(String),
    /// The app installs its own `Bundle` with `.i18n(...)` — from embedded
    /// files, a translation-management service, memory. That bundle takes
    /// precedence over any filesystem load, so the keys this generator wrote to
    /// disk will never reach it, and every generated label renders as a
    /// placeholder even though generation and `t!`'s compile-time check both
    /// succeeded. `main.rs` is left alone (swapping someone's bundle for a
    /// filesystem load would be worse) and the caller warns.
    CustomBundle,
    /// No real `.routes(` call was found, so there is nowhere safe to insert.
    /// The caller surfaces this as a plan warning rather than writing the call
    /// into a comment, where it would silently never run.
    NoAnchor,
}

/// The body braces of the innermost `fn` containing `at`.
///
/// Used where the question really is per-FUNCTION rather than per-chain: the
/// locale install is a statement of its own (`let app =
/// app.embedded_locales(&…);`), not a link in the builder chain, so "is this
/// production?" is answered by which function it sits in.
fn enclosing_body(src: &str, at: usize) -> Option<(usize, usize)> {
    real_offsets(src, "fn ")
        .into_iter()
        .filter(|&fn_at| fn_at < at)
        .filter_map(|fn_at| brace_block(src, fn_at))
        .filter(|&(open, close)| open < at && at < close)
        .max_by_key(|&(open, _)| open)
}

/// The `.routes(` calls belonging to builders the BINARY runs, or empty when
/// that cannot be told apart from a helper's.
///
/// A builder inside `fn main`'s body is unambiguous. Otherwise `main` delegates
/// (`fn main() { build_app().serve() }`), and the only safe read is when the
/// file holds exactly one builder. Picking the first of several was a guess
/// dressed as a default: with a preview helper above `build_app()` it wires the
/// preview, production renders raw keys, and the idempotency guard stops any
/// later run from correcting it. A refusal the caller can warn about is worth
/// more than a coin flip that cannot be retried.
fn production_routes_anchors(main_rs: &str) -> Vec<usize> {
    // Token-wise, like every other method detection here: `.routes
    // (routes![…])` and a comment before the paren are valid Rust, and missing
    // the anchor makes the whole wiring a no-op — the scaffold emits translated
    // views and never installs the bundle to resolve them.
    let offsets: Vec<usize> = method_call_offsets(main_rs, ".routes").collect();
    // On an IDENTIFIER boundary: `fn main_preview()` is a different function
    // that happens to start with the same letters.
    let main_fn_at = real_offsets(main_rs, "fn main").into_iter().find(|&at| {
        main_rs[at + "fn main".len()..]
            .chars()
            .next()
            .is_none_or(|c| !c.is_alphanumeric() && c != '_')
    });
    // EVERY builder inside `main`, not just the first: a conditionally-built
    // app has one per branch, and each is production.
    if let Some((open, close)) = main_fn_at.and_then(|at| brace_block(main_rs, at)) {
        let inside: Vec<usize> = offsets
            .iter()
            .copied()
            .filter(|&o| o > open && o < close)
            .collect();
        if !inside.is_empty() {
            return inside;
        }
    }
    // `main` delegates. A `#[cfg(test)]` builder is not a candidate at all —
    // it cannot be the one the binary runs — and excluding it keeps the very
    // common `build_app()` + `#[cfg(test)] test_app()` shape working. What is
    // left must be unambiguous: two ordinary builders (a preview helper beside
    // the real one) is a coin flip, and a wrong flip cannot be retried, since
    // the inserted call makes every later run a no-op.
    let candidates: Vec<usize> = offsets
        .iter()
        .copied()
        .filter(|&o| !in_cfg_test(main_rs, o))
        .collect();
    match candidates.as_slice() {
        [only] => vec![*only],
        _ => Vec::new(),
    }
}

/// Whether `at` sits inside a `#[cfg(test)]` item — the fixture module or
/// function, whose builder is never the one the binary runs.
fn in_cfg_test(src: &str, at: usize) -> bool {
    real_offsets(src, "#[cfg(test)]")
        .into_iter()
        .filter_map(|attr| cfg_item_span(src, attr))
        .any(|(start, end)| start < at && at < end)
}

/// The span of the item an attribute at `attr` applies to.
///
/// An item is EITHER brace-delimited (`mod`, `fn`, `impl`) or
/// semicolon-terminated (`static`, `const`, `use`, `type`). Taking the next
/// brace unconditionally walks straight past a `static … ;` and lands on some
/// unrelated later block — which both fails to recognise the test-only static
/// AND drags whatever that later block is into the `cfg(test)` region. A
/// `#[cfg(test)] static EMBEDDED_LOCALES` read as production is the concrete
/// harm: the install gets added to production code referring to a symbol that
/// does not exist there, and the `--embed` release stops compiling.
fn cfg_item_span(src: &str, attr: usize) -> Option<(usize, usize)> {
    const ATTR: &str = "#[cfg(test)]";
    let after = attr + ATTR.len();
    let rest = &src[after..];
    let brace = real_offsets(rest, "{").first().copied();
    let semi = real_offsets(rest, ";").first().copied();
    match (brace, semi) {
        // Whichever terminator comes first decides which kind of item this is.
        (Some(b), Some(s)) if s < b => Some((attr, after + s)),
        (None, Some(s)) => Some((attr, after + s)),
        (Some(_), _) => brace_block(src, after).map(|(_, close)| (attr, close)),
        (None, None) => None,
    }
}

/// Insert `.i18n_auto()` into the `AppBuilder` chain in `main.rs` so the
/// generated `t!` lookups actually resolve (AC4's "zero further config").
///
/// Inserted immediately before the first REAL `.routes(` call — the same anchor
/// `autumn new --with-i18n` uses, but found with a comment/string-aware scan
/// (see [`real_offsets`]). A `main.rs` that already installs a
/// bundle — `.i18n_auto()` or an explicit `.i18n(...)` — is left untouched: an
/// app that built its own `Bundle` from embedded files or a
/// translation-management service must not have it swapped for a filesystem
/// load.
pub(super) fn ensure_i18n_auto(main_rs: &str) -> I18nAutoWiring {
    // WHICH builders are production is decided first, and everything else is
    // asked about those builders rather than about the file. A `main.rs` can
    // hold several — a preview helper, a `#[cfg(test)]` fixture — and file-wide
    // questions gave wrong answers on ordinary layouts: a `.i18n(test_bundle())`
    // in a fixture reported the whole app as custom-bundled and left production
    // unwired, and an `.i18n_auto()` on the fixture reported it as already done.
    let anchors = production_routes_anchors(main_rs);
    if anchors.is_empty() {
        return I18nAutoWiring::NoAnchor;
    }
    // EVERY production branch, not just the first, and each judged ON ITS OWN.
    // `main` may build the app conditionally — one `.routes(` per configuration
    // branch — and one branch carrying `.i18n_auto()` says nothing about its
    // sibling. A hand-installed `.i18n(...)` is asked about the enclosing
    // function instead of the chain; [`custom_bundle_before`] carries the
    // reasoning for the difference.
    //
    // A chain with its own bundle is LEFT ALONE rather than blocking the rest.
    // `.i18n_auto()` CLEARS a preloaded bundle and switches to filesystem
    // loading, so wiring it into that chain would replace the app's embedded or
    // TMS-backed bundle and can panic when nothing is on disk — but that is a
    // reason to skip THAT chain, not to abandon its siblings to raw keys.
    let mut custom = false;
    let mut pending = Vec::new();
    for at in anchors {
        if custom_bundle_before(main_rs, at) {
            custom = true;
        } else if !chain_already_wired(main_rs, at) {
            pending.push(at);
        }
    }
    if pending.is_empty() {
        // Nothing to add. Say WHY: a file whose only production chain installs
        // its own bundle is reported, so the caller warns rather than claiming
        // success.
        return if custom {
            I18nAutoWiring::CustomBundle
        } else {
            I18nAutoWiring::Wired(main_rs.to_owned())
        };
    }

    // Applied back-to-front so each insertion leaves the earlier offsets valid.
    let mut out = main_rs.to_owned();
    for at in pending.into_iter().rev() {
        // Reuse the anchor line's own indentation so the inserted call sits in
        // the builder chain rather than at some arbitrary column.
        let line_start = out[..at].rfind('\n').map_or(0, |i| i + 1);
        if out[line_start..at].trim_start().is_empty() {
            let indent: String = out[line_start..at]
                .chars()
                .take_while(|c| c.is_whitespace())
                .collect();
            out = format!(
                "{}{indent}.i18n_auto()\n{}",
                &out[..line_start],
                &out[line_start..]
            );
        } else {
            // `.routes(` is not the first token on its line (e.g. a single-line
            // builder chain). Insert inline, which is still valid Rust.
            out = format!("{}.i18n_auto(){}", &out[..at], &out[at..]);
        }
    }
    I18nAutoWiring::Wired(out)
}

/// Whether the builder chain ending at `.routes(` offset `at` already calls
/// `.i18n_auto()`.
///
/// The chain is delimited by the previous `;` or `{` — the start of the
/// statement this call belongs to — so one branch being wired says nothing
/// about its sibling.
fn chain_already_wired(src: &str, at: usize) -> bool {
    method_call_offsets(&src[chain_start(src, at)..at], ".i18n_auto")
        .next()
        .is_some()
}

/// Whether a bundle is already installed on the app the chain at `at` builds.
///
/// Scoped to the enclosing FUNCTION BODY up to `at`, not to the chain — and
/// deliberately at a different granularity from [`chain_already_wired`] next to
/// it, because the two fail in opposite directions:
///
///   * Missing a custom bundle inserts `.i18n_auto()`, which CLEARS the
///     preloaded bundle and switches to a filesystem load — the app silently
///     loses its embedded or TMS-backed translations, and panics at startup
///     when nothing is on disk.
///   * Seeing one that is not there skips the chain, and the caller warns.
///
/// So this one errs toward finding it. `let app = app.i18n(custom_bundle());`
/// followed by `let app = app.routes(…);` is the ordinary builder rebinding —
/// one app, two statements — and a chain-scoped search sees only the second and
/// calls the app unbundled.
///
/// The BLOCK, though, not the whole function: a `main` that builds the app
/// conditionally puts each branch in a block of its own, and one branch's
/// hand-installed bundle genuinely says nothing about its sibling. Widening
/// this to the enclosing `fn` would leave that sibling unwired and rendering
/// raw keys. A block is exactly the scope a rebinding can cross and a branch
/// cannot.
///
/// Stopping at `at` keeps a bundle installed AFTER the routes chain out of it:
/// that one runs later and overrides `.i18n_auto()` rather than being clobbered
/// by it, so there is nothing to protect.
fn custom_bundle_before(src: &str, at: usize) -> bool {
    let start = enclosing_block_start(src, at);
    method_call_offsets(&src[start..at], ".i18n")
        .next()
        .is_some()
}

/// Just inside the innermost block or delimiter pair containing `at`, or 0 at
/// file scope.
///
/// [`chain_start`] without its statement rule — the same balanced backward scan
/// over real code, stopping one level out instead of at the previous `;`.
fn enclosing_block_start(src: &str, at: usize) -> usize {
    let mut depth = 0usize;
    for &(offset, byte) in delimiter_marks(src, at).iter().rev() {
        match byte {
            b')' | b']' | b'}' => depth += 1,
            b'(' | b'[' | b'{' => {
                let Some(next) = depth.checked_sub(1) else {
                    return offset + 1;
                };
                depth = next;
            }
            // A `;` is a statement boundary, which is exactly what this scan
            // is meant to cross.
            _ => {}
        }
    }
    0
}

/// Real-code delimiter positions before `at`, in source order, so a `;` or
/// brace inside a string or comment is never mistaken for structure.
fn delimiter_marks(src: &str, at: usize) -> Vec<(usize, u8)> {
    let mut marks: Vec<(usize, u8)> = Vec::new();
    for (needle, byte) in [
        (";", b';'),
        ("{", b'{'),
        ("}", b'}'),
        ("(", b'('),
        (")", b')'),
        ("[", b'['),
        ("]", b']'),
    ] {
        marks.extend(
            real_offsets(&src[..at], needle)
                .into_iter()
                .map(|o| (o, byte)),
        );
    }
    marks.sort_unstable();
    marks
}

/// Start of the statement the call at `at` belongs to.
///
/// Balanced-delimiter aware, and reading only REAL code. A raw `rfind` for the
/// previous `;` or `{` stops inside anything nested between the chain's start
/// and this call — `.layer(from_fn(|req, next| async move { … }))` is ordinary
/// middleware, and its closing brace looked like the statement boundary. That
/// truncated chain hid an earlier `.i18n(...)`, so `.i18n_auto()` was inserted
/// into a chain that already had a bundle and CLEARED it.
fn chain_start(src: &str, at: usize) -> usize {
    let mut depth = 0usize;
    for &(offset, byte) in delimiter_marks(src, at).iter().rev() {
        match byte {
            b')' | b']' | b'}' => depth += 1,
            b'(' | b'[' => {
                // An unmatched opener encloses this call: the chain begins just
                // inside it (an argument position, e.g. `foo(App::new()…)`).
                let Some(next) = depth.checked_sub(1) else {
                    return offset + 1;
                };
                depth = next;
            }
            b'{' => {
                let Some(next) = depth.checked_sub(1) else {
                    return offset + 1;
                };
                depth = next;
            }
            b';' if depth == 0 => return offset + 1,
            _ => {}
        }
    }
    0
}

